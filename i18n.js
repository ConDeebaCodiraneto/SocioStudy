/** Plain string lookup. */
function t(key) {
  const v = I18N.STRINGS[I18N.lang][key] != null ? I18N.STRINGS[I18N.lang][key] : I18N.STRINGS.en[key];
  return v == null ? key : v;
}

/** Parameterized string lookup — the value is a function of the args. */
function tp(key, ...args) {
  const v = t(key);
  return typeof v === 'function' ? v(...args) : v;
}

/** Localized gender / status labels (statuses are stored as English keys). */
function genderLabel(g) { return t('gender.' + g); }
function genderLabelPlural(g) { return t('genderPl.' + g); }
function statusLabel(s) { return t('status.' + s); }
